import {test,expect} from '@playwright/test';

test('free medieval knight, real sword/shield, greatsword and native melee animations',async({page},info)=>{
 const pageErrors=[],resourceFailures=[];
 page.on('pageerror',e=>pageErrors.push(e.message));
 page.on('requestfailed',r=>{resourceFailures.push(r.url());console.log('RESOURCE_FAILED',r.url(),r.failure()?.errorText)});
 page.on('response',r=>{if(r.status()>=400)console.log('HTTP_ERROR',r.status(),r.url())});
 page.on('console',m=>{if(m.type()==='warning'||m.type()==='error')console.log('BROWSER_LOG',m.type(),m.text())});
 await page.goto('/?debug=1',{waitUntil:'domcontentloaded'});
 const state=()=>page.evaluate(()=>window.__wanderlandsDebug?.state());
 await expect.poll(async()=>!!(await state()),{timeout:30000}).toBe(true);
 await expect.poll(async()=> (await state()).medieval.ready,{timeout:90000}).toBe(true);
 await expect.poll(async()=> (await state()).medieval.twoHandReady,{timeout:90000}).toBe(true);
 const initial=await state();
 console.log('MEDIEVAL_ASSETS',JSON.stringify(initial.medieval));
 expect(initial.medieval.assetError).toBeNull();
 expect(initial.medieval.animationError).toBeNull();
 expect(initial.medieval.hasRealSword).toBe(true);
 expect(initial.medieval.hasRealShield).toBe(true);
 expect(initial.medieval.animationCount).toBeGreaterThanOrEqual(23);
 for(const clip of ['Melee_1H_Attack_Slice_Horizontal','Melee_2H_Attack_Chop','Melee_2H_Attack_Slice','Melee_2H_Idle','Melee_Blocking','Running_A','Walking_A'])
   expect(initial.medieval.clipNames).toContain(clip);
 const ammo=initial.weapons.ammo;
 await page.keyboard.press('m');
 await expect.poll(async()=> (await state()).medieval.active).toBe(true);
 await expect.poll(async()=> (await state()).medieval.characterVisible).toBe(true);
 await expect.poll(async()=> (await state()).medieval.oneHandVisible).toBe(true);
 expect((await state()).medieval.shieldVisible).toBe(true);
 expect((await state()).weapons.medievalMode).toBe(true);
 expect((await state()).weapons.worldGunVisible).toBe(false);
 await page.waitForTimeout(500);
 await page.screenshot({path:info.outputPath('sword-and-shield.png')});
 await page.locator('canvas').click({position:{x:160,y:180}});
 await expect.poll(async()=> (await state()).medieval.attacks).toBe(1);
 await expect.poll(async()=> (await state()).medieval.currentClip).toContain('Melee_1H_Attack');
 await page.screenshot({path:info.outputPath('one-handed-sword-attack.png')});
 // Hold the shield guard button; a one-frame right click should not latch blocking.
 await expect.poll(async()=> (await state()).medieval.attackRemaining,{timeout:11000}).toBe(0);
 await page.mouse.move(165,200);
 await page.mouse.down({button:'right'});
 await expect.poll(async()=> (await state()).medieval.currentClip,{timeout:7000}).toBe('Melee_Blocking');
 await page.screenshot({path:info.outputPath('shield-block.png')});
 await page.mouse.up({button:'right'});
 await page.keyboard.press('q');
 await expect.poll(async()=> (await state()).medieval.style).toBe('greatsword');
 const two=await state();
 expect(two.medieval.twoHandVisible).toBe(true);
 expect(two.medieval.shieldVisible).toBe(false);
 expect(two.medieval.oneHandVisible).toBe(false);
 await page.waitForTimeout(400);
 await expect.poll(async()=> (await state()).medieval.currentClip).toBe('Melee_2H_Idle');
 await page.screenshot({path:info.outputPath('greatsword-idle.png')});
 await page.locator('canvas').click({position:{x:170,y:185}});
 await expect.poll(async()=> (await state()).medieval.currentClip).toContain('Melee_2H_Attack');
 await page.screenshot({path:info.outputPath('greatsword-swing.png')});
 await page.evaluate(()=>window.__wanderlandsDebug.teleportLake());
 await expect.poll(async()=> (await state()).swimming,{timeout:18000}).toBe(true);
 await expect.poll(async()=> (await state()).medieval.characterVisible).toBe(false);
 await page.keyboard.press('m');
 await expect.poll(async()=> (await state()).medieval.active).toBe(false);
 await expect.poll(async()=> (await state()).weapons.medievalMode).toBe(false);
 expect((await state()).weapons.ammo).toBe(ammo);
 expect(pageErrors).toEqual([]);
 expect(resourceFailures).toEqual([]);
});
