import { test, expect } from '@playwright/test';

test('rifle uses CC0 two-handed clips while pistol retains separate originals; swimming head stays up',async({page},testInfo)=>{
 const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('requestfailed',r=>console.log('FAILED_ASSET',r.url(),r.failure()?.errorText));
 page.on('console',m=>{if(m.type()==='warning'||m.type()==='error')console.log('BROWSER',m.type(),m.text())});
 await page.goto('/?debug=1&mode=guns',{waitUntil:'domcontentloaded'});
 const state=()=>page.evaluate(()=>window.__wanderlandsDebug?.state());
 await expect.poll(async()=>!!(await state()),{timeout:45000}).toBe(true);
 await expect.poll(async()=> (await state()).characterClipNames?.length>20,{timeout:45000}).toBe(true);
 await expect.poll(async()=> (await state()).weapons.loaded.every(x=>x.loaded),{timeout:90000}).toBe(true);
 await expect.poll(async()=> (await state()).rifleAnimations,{timeout:90000}).toMatchObject({ready:true});
 let s=await state();
 console.log('RIFLE_SOURCE',JSON.stringify(s.rifleAnimations));
 expect(s.rifleAnimations.clips).toHaveProperty('aim');
 expect(s.rifleAnimations.clips).toHaveProperty('shoot');
 expect(s.rifleAnimations.clips).toHaveProperty('reload');
 expect(s.rifleAnimations.clips.aim.tracks).toBeGreaterThan(5);
 expect(s.rifleAnimations.clips.shoot.tracks).toBeGreaterThan(5);
 expect(s.rifleAnimations.mappedBones.some(x=>/handR$/i.test(x))).toBe(true);
 // Pistol action selection stays native and separate.
 expect(s.weapons.active).toBe('p226');
 await expect.poll(async()=> (await state()).activeCharacterState,{timeout:7000}).toBe('pistolIdle');
 expect((await state()).rifleAnimations.active).toBe('none');
 await page.screenshot({path:testInfo.outputPath('pistol-unchanged.png')});
 await page.keyboard.press('q');
 await expect.poll(async()=> (await state()).weapons.active,{timeout:4000}).toBe('m4a1');
 await expect.poll(async()=> (await state()).rifleAnimations.active,{timeout:6000}).toBe('aim');
 s=await state();
 expect(s.activeCharacterState).not.toBe('pistolIdle');
 await page.screenshot({path:testInfo.outputPath('rifle-aim.png')});
 const ammo=s.weapons.ammo;
 await page.locator('canvas').click({position:{x:150,y:100}});
 await expect.poll(async()=> (await state()).weapons.ammo).toBeLessThan(ammo);
 await expect.poll(async()=> (await state()).rifleAnimations.active,{timeout:5000}).toBe('shoot');
 await page.waitForTimeout(100);
 await page.screenshot({path:testInfo.outputPath('rifle-shoot.png')});
 await page.keyboard.press('r');
 await expect.poll(async()=> (await state()).weapons.reloading,{timeout:5000}).toBe(true);
 await expect.poll(async()=> (await state()).rifleAnimations.active,{timeout:5000}).toBe('reload');
 await page.screenshot({path:testInfo.outputPath('rifle-reload.png')});
 await expect.poll(async()=> (await state()).weapons.reloading,{timeout:15000}).toBe(false);
 await page.keyboard.press('q');
 await expect.poll(async()=> (await state()).weapons.active,{timeout:4000}).toBe('p226');
 await expect.poll(async()=> (await state()).activeCharacterState,{timeout:7000}).toBe('pistolIdle');
 await expect.poll(async()=> (await state()).rifleAnimations.active,{timeout:7000}).toBe('none');
 // Existing physics and authored swim strokes remain; only body pitch changes.
 await page.evaluate(()=>window.__wanderlandsDebug.teleportLake());
 await expect.poll(async()=> (await state()).swimming,{timeout:12000}).toBe(true);
 await page.keyboard.down('w');
 await expect.poll(async()=> (await state()).activeCharacterState,{timeout:12000}).toBe('swim');
 await expect.poll(async()=> (await state()).swimBodyTilt,{timeout:12000}).toBeGreaterThan(-.24);
 const tilt=(await state()).swimBodyTilt;
 expect(tilt).toBeLessThan(-.02);
 await page.screenshot({path:testInfo.outputPath('swim-tilt.png')});
 await page.keyboard.up('w');
 expect(errors).toEqual([]);
});
